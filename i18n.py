TEXT = {row[0]: dict(zip(LANGS, row[1:])) for row in _TEXT_ROWS}


def tr(key, **kw):
    """Tłumaczenie komunikatu serwera w języku żądania (nagłówek X-Lang)."""
    entry = TEXT.get(key)
    if not entry:
        return key
    s = entry.get(getattr(_LANG, 'v', 'pl')) or entry['pl']
    return s.format(**kw) if kw else s


def status_short(st):
    return tr('st_short_' + st) if ('st_short_' + st) in TEXT else st


def status_long(st):
    return tr('st_long_' + st) if ('st_long_' + st) in TEXT else st


def reason_text(code):
    if code.startswith('r_root_down:'):
        return tr('r_root_down', status=status_short(code.split(':', 1)[1]))
    return tr(code) if code in TEXT else code


def set_lang(value):
    v = (value or 'pl').strip().lower()[:2]
    _LANG.v = v if v in LANGS else 'pl'
